-- Sakura · Sistema de gestión de pedidos y reservas para restaurante.
-- Esquema y datos iniciales para Supabase (Postgres).
-- Ejecútalo entero en Supabase → SQL Editor → New query → Run.
-- Se puede ejecutar más de una vez: no borra datos y solo inserta los de ejemplo si las tablas están vacías.

-- La versión anterior guardaba la carta en `plato`, con la categoría como texto. Ahora son `categoria` y `producto`.
drop table if exists plato;

-- ─────────────────────────────────────────────────────────────
-- Usuarios y roles (RF-08, RF-11)
-- ─────────────────────────────────────────────────────────────

create table if not exists usuario (
  id            bigint generated by default as identity primary key,
  nombre        varchar(80)  not null,
  email         varchar(120) not null unique,
  password_hash varchar(100) not null,
  rol           varchar(20)  not null default 'CLIENTE' check (rol in ('ADMIN', 'MESERO', 'CLIENTE')),
  activo        boolean      not null default true,
  creado_en     timestamptz  not null default now()
);

-- ─────────────────────────────────────────────────────────────
-- Menú (RF-01, RF-02, RF-10)
-- ─────────────────────────────────────────────────────────────

create table if not exists categoria (
  id          bigint generated by default as identity primary key,
  nombre      varchar(40)  not null unique,
  descripcion varchar(200),
  orden       integer      not null default 0
);

create table if not exists producto (
  id           bigint generated by default as identity primary key,
  categoria_id bigint        not null references categoria (id) on delete restrict,
  nombre       varchar(120)  not null,
  descripcion  varchar(300),
  precio       numeric(10, 2) not null check (precio >= 0),
  disponible   boolean       not null default true,
  destacado    boolean       not null default false,
  orden        integer       not null default 0,
  imagen       varchar(200)
);

-- Foto del producto (añadida después): ruta pública del WebP de 800 px.
alter table producto add column if not exists imagen varchar(200);

create index if not exists producto_categoria_idx on producto (categoria_id);

-- ─────────────────────────────────────────────────────────────
-- Mesas y pedidos (RF-03 a RF-07, RF-09)
-- ─────────────────────────────────────────────────────────────

create table if not exists mesa (
  id        bigint generated by default as identity primary key,
  numero    integer     not null unique check (numero > 0),
  capacidad integer     not null check (capacidad > 0),
  ubicacion varchar(40),
  estado    varchar(20) not null default 'DISPONIBLE' check (estado in ('DISPONIBLE', 'OCUPADA'))
);

create table if not exists pedido (
  id             bigint generated by default as identity primary key,
  mesa_id        bigint        not null references mesa (id) on delete restrict,
  usuario_id     bigint        references usuario (id) on delete set null,
  estado         varchar(20)   not null default 'PENDIENTE'
                 check (estado in ('PENDIENTE', 'EN_PREPARACION', 'SERVIDO', 'PAGADO', 'CANCELADO')),
  total          numeric(12, 2) not null default 0 check (total >= 0),
  notas          varchar(300),
  creado_en      timestamptz   not null default now(),
  actualizado_en timestamptz   not null default now()
);

create index if not exists pedido_mesa_idx on pedido (mesa_id);
create index if not exists pedido_creado_idx on pedido (creado_en);

-- El precio unitario se copia del producto al añadirlo, para que el pedido no cambie si luego cambia la carta.
create table if not exists detalle_pedido (
  id              bigint generated by default as identity primary key,
  pedido_id       bigint         not null references pedido (id) on delete cascade,
  producto_id     bigint         not null references producto (id) on delete restrict,
  cantidad        integer        not null check (cantidad > 0),
  precio_unitario numeric(10, 2) not null check (precio_unitario >= 0),
  subtotal        numeric(12, 2) not null check (subtotal >= 0),
  unique (pedido_id, producto_id)
);

-- ─────────────────────────────────────────────────────────────
-- Reservas
-- ─────────────────────────────────────────────────────────────

-- Turnos en los que se puede reservar. La capacidad es el máximo de personas por turno.
create table if not exists turno (
  id            bigint generated by default as identity primary key,
  hora          time    not null unique,
  capacidad_max integer not null check (capacidad_max > 0),
  activo        boolean not null default true
);

-- Días en que el restaurante no abre (festivos, vacaciones).
create table if not exists cierre (
  id     bigint generated by default as identity primary key,
  fecha  date not null unique,
  motivo varchar(120)
);

create table if not exists reserva (
  id         bigint generated by default as identity primary key,
  codigo     varchar(12)  not null unique,
  fecha      date         not null,
  hora       time         not null,
  personas   integer      not null check (personas between 1 and 8),
  nombre     varchar(80)  not null,
  email      varchar(120) not null,
  telefono   varchar(30)  not null,
  notas      varchar(500),
  estado     varchar(20)  not null default 'PENDIENTE'
             check (estado in ('PENDIENTE', 'CONFIRMADA', 'CANCELADA')),
  creada_en  timestamptz  not null default now()
);

create index if not exists reserva_fecha_hora_idx on reserva (fecha, hora);

-- ─────────────────────────────────────────────────────────────
-- Contenido de la landing
-- ─────────────────────────────────────────────────────────────

create table if not exists experiencia (
  id          bigint generated by default as identity primary key,
  nombre      varchar(120)   not null,
  descripcion varchar(300)   not null,
  precio      numeric(10, 2) not null,
  personas    integer        not null default 1,
  etiqueta    varchar(40),
  orden       integer        not null default 0
);

create table if not exists faq (
  id        bigint generated by default as identity primary key,
  pregunta  varchar(200)  not null,
  respuesta varchar(1000) not null,
  orden     integer       not null default 0
);

-- ─────────────────────────────────────────────────────────────
-- Seguridad
-- ─────────────────────────────────────────────────────────────
-- Supabase publica las tablas de `public` en su API REST. Con RLS activo y sin políticas, nadie puede leerlas ni
-- escribirlas desde esa API: todo pasa por el backend Spring, que conecta con el rol `postgres` y no se ve afectado.

alter table usuario        enable row level security;
alter table categoria      enable row level security;
alter table producto       enable row level security;
alter table mesa           enable row level security;
alter table pedido         enable row level security;
alter table detalle_pedido enable row level security;
alter table turno          enable row level security;
alter table cierre         enable row level security;
alter table reserva        enable row level security;
alter table experiencia    enable row level security;
alter table faq            enable row level security;

